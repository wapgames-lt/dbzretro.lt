    return $config[$randomKey];
}


function getRandomMission(array $user)
{
    $eventMission = getMissionByEvent();

    if ($eventMission) {
        return $eventMission;
    }

    $missionByLevel = getRandomMissionByLevel($user);

    if ($missionByLevel) {
        return $missionByLevel;
    }

    return [];
}

function getRandomMissionByLevel(array $user)
{
    if ($user['lygis'] < 15) {
        return getRandomNoobLevelMission();
    }

    if ($user['lygis'] < 30) {
        return getRandomLowLevelMission();
    }

    if ($user['lygis'] < 45) {
        return getRandomMidLevelMission();
    }

    if ($user['lygis'] < 60) {
        return getRandomHighLevelMission();
    }

    if ($user['lygis'] < 100) {
        return getRandomMasterLevelMission();
    }

    if ($user['lygis'] < 140) {
        return getRandomGrandMasterLevelMission();
    }

    if ($user['lygis'] < 200) {
        return getRandomChallengerLevelMission();
    }

    if ($user['lygis'] < 300) {
        return getRandomGodLevelMission();
    }

    return [];
}

function getMissionById($missionId)
{
    global $missions;

    foreach ($missions as $mission) {
        if ($mission['id'] === $missionId) {
            return $mission;
        }
    }

    return [];
}

function getRandomRewardImage($missionConfig)
{
    $images = $missionConfig['rewards']['images'];
    if (!$images) {
        return null;
    }

    $randomKey = array_rand($images);

    return $images[$randomKey];
}

function getMissionByEvent()
{
    if (isChristmas()) {
        return getRandomChristmasMission();
    }

    if (isNewYear()) {
        return getRandomNewYearMission();
    }

    return [];
}

function isChristmas()
{
    $month = date('n');
    $day = date('j');

    if ($month !== '12') {
        return false;
    }

    $christmasDays = [
        '25',
        '26',
    ];

    if (!in_array($day, $christmasDays, true)) {
        return false;
    }

    return true;
}

function isNewYear()
{
    $month = date('n');
    $day = date('j');

    if ($month !== '1') {
        return false;
    }

    if ($day !== '1') {
        return false;
    }

    return true;
}