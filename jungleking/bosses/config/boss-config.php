function isChristmas()
{
    $month = date('n');
    $day = date('j');

    if ($month !== '12') {
        return false;
    }

    $christmasDays = [
        '25',
        '26',
    ];
    return in_array($day, $christmasDays, true);
}

function isNewYear()
{
    $month = date('n');
    $day = date('j');

    if ($month !== '1') {
        return false;
    }
    return $day === '1';
}

function getRandomBossByConfig(array $config)
{
    $randomKey = array_rand($config);

    return $config[$randomKey];
}

function getRandomChristmasBoss()
{
    global $christmasBossList;

    return getRandomBossByConfig($christmasBossList);
}
