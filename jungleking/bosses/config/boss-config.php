function getRandomBoss(array $user)
{
    global $bossList;

    if ($eventBoss = getBossByEvent()) {
        return $eventBoss;
    }

    $bossIds = [];
    foreach ($bossList as $boss) {
        $min = $user['lygis'] - 30;
        $max = $user['lygis'] + 10;
        if ($min <= $boss['level'] && $boss['level'] <= $max) {
            $bossIds[] = $boss['id'];
        }
    }

    if ($bossIds !== []) {
        $randomKey = array_rand($bossIds);
        $randomBossId = $bossIds[$randomKey];

        return getBossById($randomBossId);
    }

    return getRandomBossByConfig($bossList);
}

function getBossById($bossId)
{
    global $bossList, $christmasBossList;

    $bossList = array_merge($bossList, $christmasBossList);

    foreach ($bossList as $boss) {
        if ($boss['id'] === $bossId) {
            return $boss;
        }
    }

    return [];
}

function getRandomRewardImage($missionConfig)
{
    $images = $missionConfig['rewards']['images'];
    if (!$images) {
        return null;
    }

    $randomKey = array_rand($images);

    return $images[$randomKey];
}

function getRandomVideo($bossConfig)
{
    $videos = $bossConfig['videos'];
    if (!$videos) {
        return null;
    }

    $randomKey = array_rand($videos);

    return $videos[$randomKey];
}

